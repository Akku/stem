#!/usr/bin/env python3
"""Write each agent's hook config and docs/agent/HOOKS.md from scripts/hooks/manifest.json (the one source).

  scripts/hooks-sync.py           write .claude/settings.json (hooks part), .codex/hooks.json, docs/agent/HOOKS.md
  scripts/hooks-sync.py --check   change nothing; exit 1 and name the files that differ from the manifest
  --root DIR                      project folder (default: the folder above scripts/)

Only hook entries that call a script named in the manifest are owned by STEM. The user's own hooks, permissions and every other
setting stay as they are. A file is rewritten only when its content differs: Codex binds hook trust to the file's hash, so an
unchanged file keeps its trust and a changed one must be reviewed again in Codex (/hooks)."""
import json, pathlib, re, sys

TEMPLATES = {
    ("claude-code", "sh"): 'cd "$CLAUDE_PROJECT_DIR" && bash "$CLAUDE_PROJECT_DIR/{s}"',
    ("claude-code", "py"): 'for p in python3 python "py -3"; do $p -c "import sys; sys.exit(sys.version_info[0] < 3)" 2>/dev/null && {{ $p "$CLAUDE_PROJECT_DIR/{s}" 2>/dev/null; break; }}; done; true',
    ("codex", "sh"): 'root="$(git rev-parse --show-toplevel)" && cd "$root" && bash {s}',
    ("codex", "py"): 'root="$(git rev-parse --show-toplevel)" && cd "$root" && python3 {s} 2>/dev/null; true',
}


def load(path):
    try: return json.loads(path.read_text())
    except (OSError, ValueError): return {}


def owned(command, scripts):
    return any(re.search(r"(^|[\s\"'/])" + re.escape(s) + r"($|[\s\"'])", command) for s in scripts)


def build(existing, manifest, agent):
    """The agent's config with STEM's hook entries replaced by the manifest's; everything else kept."""
    scripts = [g["script"] for g in manifest["guards"]]
    hooks = {}
    for g in manifest["guards"]:  # STEM entries first, in manifest order
        w = g.get("wiring", {}).get(agent)
        if not w: continue
        kind = "py" if g["script"].endswith(".py") else "sh"
        entry = {"matcher": w["matcher"]} if w.get("matcher") else {}
        entry["hooks"] = [{"type": "command", "command": TEMPLATES[(agent, kind)].format(s=g["script"])}]
        hooks.setdefault(w["event"], []).append(entry)
    for event, entries in (existing.get("hooks") or {}).items():  # then what the user added
        for e in entries if isinstance(entries, list) else []:
            keep = [h for h in e.get("hooks", []) if not owned(str(h.get("command", "")), scripts)]
            if keep: hooks.setdefault(event, []).append({**e, "hooks": keep})
    out = {k: v for k, v in existing.items() if k != "hooks"}
    if hooks: out["hooks"] = hooks
    return out


def matrix(manifest):
    agents = manifest["agents"]
    lines = ["# Hooks and guards per agent", "",
             "Generated by `scripts/hooks-sync.py` from `scripts/hooks/manifest.json`. Do not edit; change the manifest and run the script.",
             "Read when adding an agent, when a hook API changed, or in the `port-check` skill.", "",
             "| Guard | Purpose | " + " | ".join(a["name"] for a in agents.values()) + " | Without a hook |", "| --- | --- | " + "--- | " * len(agents) + "--- |"]
    for g in manifest["guards"]:
        cells = []
        for key in agents:
            w = g.get("wiring", {}).get(key)
            if g.get("git"): cells.append("git hook")
            elif w: cells.append("`%s`" % w["event"] + (" on `%s`" % w["matcher"].replace("|", "\\|") if w.get("matcher") else ""))
            else: cells.append("no hook")
        lines.append("| `%s` | %s | %s | %s |" % (g["script"], g["purpose"], " | ".join(cells), g["fallback"]))
    lines += ["", "## Evidence per agent", ""] + ["- **%s:** %s." % (a["name"], a["evidence"]) for a in agents.values()]
    lines += ["", "## Project choices", "",
              "A project switches a guard off in `docs/agent/stem-config.json`, which the scripts read at run time: `{\"context_warning\": false}`, `{\"large_read_warning\": false}`. "
              "The hook entries stay as shipped. Never edit `.claude/settings.json` hooks or `.codex/hooks.json` for such a choice: Codex binds its trust to the file's hash and may block the edit.", ""]
    lines += ["## Changing the wiring", "",
              "1. Edit `scripts/hooks/manifest.json` (new agent: a key under `agents`, a command template in `scripts/hooks-sync.py`, a `wiring` entry per guard).",
              "2. Run `python3 scripts/hooks-sync.py`; `--check` must then pass.",
              "3. Run the session-start and hook item of the port-check checklist (`docs/agent/PORT_CHECK.md`, C1) in that agent and record the result under `evidence`.",
              "4. STEM itself: CHANGELOG entry with a `Migration:` line; a changed `.codex/hooks.json` makes Codex ask for trust again.", ""]
    return "\n".join(lines)


def main(argv):
    root = pathlib.Path(argv[argv.index("--root") + 1]) if "--root" in argv else pathlib.Path(__file__).resolve().parent.parent
    check = "--check" in argv
    manifest = json.loads((root / "scripts/hooks/manifest.json").read_text())
    drift = []
    for key, a in manifest["agents"].items():
        if not a.get("file"): continue
        path = root / a["file"]
        existing = load(path)
        want = build(existing, manifest, key)
        if want == existing and path.exists(): continue
        drift.append(a["file"])
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(want, indent=2) + "\n")
    doc, text = root / "docs/agent/HOOKS.md", matrix(manifest)
    if not doc.exists() or doc.read_text() != text:
        drift.append("docs/agent/HOOKS.md")
        if not check: doc.parent.mkdir(parents=True, exist_ok=True); doc.write_text(text)
    if check and drift:
        print("hooks-sync: differs from scripts/hooks/manifest.json: " + ", ".join(drift) + " (run python3 scripts/hooks-sync.py)")
        return 1
    print("hooks-sync: " + ("up to date" if not drift else "written: " + ", ".join(drift)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
